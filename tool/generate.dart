// Generates the Dart side of the design values from kakao-components'
// tokens.json (written there by tools/export-tokens.js).
//
//   dart run tool/generate.dart [path/to/tokens.json]
//
// Default input: tool/tokens.json, the pinned copy this repo builds from (see
// tool/tokens.source for where it came from). Writes:
//
//   lib/src/theme/kakao_colors.g.dart      colour roles, every theme, more-contrast colours
//   lib/src/theme/kakao_tokens.g.dart      the other shared tokens (space, radius, motion…)
//   lib/src/settings/kakao_<name>_settings.g.dart   one class per ported component
//
// A settings class is built from each setting's `value` chain (not from the
// pre-resolved table), so settings follow the theme live: colour roles come
// from the KakaoColors passed in, `color-mix()` is computed at runtime, and a
// setting that follows a sibling reads that sibling. A `*padding` setting
// holding 1-4 lengths (the CSS shorthand) becomes EdgeInsets. Values a Dart type can't
// hold (calc with runtime refs, keyword lists) are listed in the class's doc
// comment as not generated; the widget handles those by hand.
//
// To port another component, add its name to [ported] and run this again.
import 'dart:convert';
import 'dart:io';

/// Components with a Flutter twin: their settings classes are generated.
const ported = [
  'button',
  'card',
  'chip',
  'combobox',
  'command-palette',
  'date-input',
  'dialog',
  'menu',
  'multi-dropdown',
  'number-input',
  'password-input',
  'popover',
  'progress',
  'select',
  'tag-input',
  'text-input',
  'textarea',
  'theme-switch',
  'time-input',
  'tooltip',
];

late Map<String, dynamic> tokens;

void main(List<String> args) {
  final input = args.isNotEmpty ? args.first : 'tool/tokens.json';
  tokens = jsonDecode(File(input).readAsStringSync()) as Map<String, dynamic>;
  if (tokens['formatVersion'] != 1) {
    stderr.writeln('generate: $input has formatVersion ${tokens['formatVersion']}, this generator reads 1');
    exit(1);
  }
  final version = tokens['version'];
  final header =
      '// GENERATED by tool/generate.dart from kakao-components v$version tokens.json.\n'
      '// Do not edit: change the web settings, export, copy tokens.json and generate.\n';

  _write('lib/src/theme/kakao_colors.g.dart', header + _colors());
  _write('lib/src/theme/kakao_tokens.g.dart', header + _sharedTokens());
  for (final name in ported) {
    _write('lib/src/settings/kakao_${_snake(name)}_settings.g.dart', header + _settings(name));
  }
  stdout.writeln('Generated from tokens.json v$version: colours, shared tokens, ${ported.length} settings classes.');
}

void _write(String path, String text) {
  File(path)
    ..parent.createSync(recursive: true)
    ..writeAsStringSync(text);
}

/* ---- names ----------------------------------------------------------------- */

const _reserved = {'default', 'switch', 'in', 'is', 'new', 'null', 'class', 'const', 'final', 'var', 'void', 'with'};

String _camel(String s) {
  final parts = s.split(RegExp(r'[-_]')).where((p) => p.isNotEmpty).toList();
  var out = parts.first + parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
  if (RegExp(r'^\d').hasMatch(out)) out = 'v$out';
  return _reserved.contains(out) ? '${out}Value' : out;
}

String _pascal(String s) {
  final c = _camel(s);
  return c[0].toUpperCase() + c.substring(1);
}

String _snake(String s) => s.replaceAll('-', '_');

String _num(num v) {
  final d = v.toDouble();
  if (d == d.roundToDouble()) return d.toStringAsFixed(1);
  return d.toString();
}

String _colorLiteral(String hex) {
  // #rrggbbaa → Color(0xAARRGGBB)
  final h = hex.substring(1);
  return 'Color(0x${(h.substring(6) + h.substring(0, 6)).toUpperCase()})';
}

/* ---- colours and themes ---------------------------------------------------- */

String _colors() {
  final themes = tokens['themes'] as Map<String, dynamic>;
  final order = (tokens['themeOrder'] as List).cast<String>();
  final roles = (themes['light']['colors'] as Map<String, dynamic>).keys.toList();
  final b = StringBuffer()
    ..writeln("import 'dart:ui' show Color;")
    ..writeln()
    ..writeln('/// The colour roles every kakao theme defines (`--kakao-color-<role>` on the web).')
    ..writeln('class KakaoColors {')
    ..writeln('  const KakaoColors({')
    ..writeAll(roles.map((r) => '    required this.${_camel(r)},\n'))
    ..writeln('  });')
    ..writeln();
  for (final r in roles) {
    b
      ..writeln('  /// `--kakao-color-$r`')
      ..writeln('  final Color ${_camel(r)};');
  }
  b
    ..writeln()
    ..writeln('  KakaoColors copyWith({')
    ..writeAll(roles.map((r) => '    Color? ${_camel(r)},\n'))
    ..writeln('  }) => KakaoColors(')
    ..writeAll(roles.map((r) => '    ${_camel(r)}: ${_camel(r)} ?? this.${_camel(r)},\n'))
    ..writeln('  );')
    ..writeln()
    ..writeln("  /// Blends two themes' colours (the theme pickers' cross-fade).")
    ..writeln('  static KakaoColors lerp(KakaoColors a, KakaoColors b, double t) => KakaoColors(')
    ..writeAll(roles.map((r) => '    ${_camel(r)}: Color.lerp(a.${_camel(r)}, b.${_camel(r)}, t)!,\n'))
    ..writeln('  );')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  bool operator ==(Object other) =>')
    ..writeln('      other is KakaoColors &&')
    ..writeln('${roles.map((r) => '      other.${_camel(r)} == ${_camel(r)}').join(' &&\n')};')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  int get hashCode => Object.hashAll([${roles.map(_camel).join(', ')}]);')
    ..writeln('}')
    ..writeln()
    ..writeln('/// One kakao theme: its colours, and the stronger colours used when the')
    ..writeln('/// platform asks for more contrast (`prefers-contrast: more` on the web).')
    ..writeln('class KakaoThemeData {')
    ..writeln(
      '  const KakaoThemeData({required this.name, required this.isDark, required this.colors, required this.highContrast});',
    )
    ..writeln('  final String name;')
    ..writeln('  final bool isDark;')
    ..writeln('  final KakaoColors colors;')
    ..writeln('  final KakaoColors highContrast;')
    ..writeln()
    ..writeln('  static const List<KakaoThemeData> all = [${order.map(_camel).join(', ')}];')
    ..writeln()
    ..writeln(
      '  static KakaoThemeData byName(String name) => all.firstWhere((t) => t.name == name, orElse: () => light);',
    );
  for (final name in order) {
    final t = themes[name] as Map<String, dynamic>;
    String block(Map<String, dynamic> cs) =>
        roles.map((r) => '      ${_camel(r)}: ${_colorLiteral(cs[r] as String)},').join('\n');
    b
      ..writeln()
      ..writeln('  static const KakaoThemeData ${_camel(name)} = KakaoThemeData(')
      ..writeln("    name: '$name',")
      ..writeln('    isDark: ${t['dark']},')
      ..writeln('    colors: KakaoColors(')
      ..writeln(block(t['colors'] as Map<String, dynamic>))
      ..writeln('    ),')
      ..writeln('    highContrast: KakaoColors(')
      ..writeln(block(t['contrastColors'] as Map<String, dynamic>))
      ..writeln('    ),')
      ..writeln('  );');
  }
  b.writeln('}');
  return b.toString();
}

/* ---- typed expressions ------------------------------------------------------- */

/// A setting's Dart type, decided from what it resolves to.
String? _dartType(Map<String, dynamic> resolved) {
  switch (resolved['type']) {
    case 'color':
      return 'Color';
    case 'length':
    case 'number':
    case 'percent':
      return 'double';
    case 'duration':
      return 'Duration';
    case 'easing':
      return 'Curve';
    case 'shadow':
      return 'List<BoxShadow>';
    case 'font':
      return 'KakaoFontSpec';
    case 'em':
      return 'KakaoEm';
    case 'viewport':
      return 'KakaoViewportLength';
    case 'calc':
      return _calcNumeric(resolved['expr'] as Map<String, dynamic>) ? 'double' : null;
    case 'list':
      return _isPadding(resolved) ? 'EdgeInsets' : null;
    default:
      return null;
  }
}

/// A space-separated list of 1-4 lengths: the CSS padding shorthand (only
/// for settings named `*padding`, see [_settings]).
bool _isPadding(Map<String, dynamic> n) {
  if (n['type'] != 'list' || n['separator'] != 'space') return false;
  final items = (n['items'] as List).cast<Map<String, dynamic>>();
  return items.isNotEmpty &&
      items.length <= 4 &&
      items.every(
        (i) => i['type'] == 'length' || (i['type'] == 'calc' && _calcNumeric(i['expr'] as Map<String, dynamic>)),
      );
}

bool _calcNumeric(Map<String, dynamic> n) {
  switch (n['type']) {
    case 'op':
      return _calcNumeric(n['left'] as Map<String, dynamic>) && _calcNumeric(n['right'] as Map<String, dynamic>);
    case 'length':
    case 'number':
      return true;
    default:
      return false;
  }
}

class _Unsupported implements Exception {
  _Unsupported(this.why);
  final String why;
}

/// Dart for a value node. [types] maps sibling setting keys to their Dart type.
String _expr(Map<String, dynamic> n, Map<String, String> types) {
  switch (n['type']) {
    case 'ref':
      if (n['token'] != null) {
        final token = n['token'] as String;
        if (token.startsWith('color-')) return 'c.${_camel(token.substring(6))}';
        return 'KakaoSharedTokens.${_camel(token)}';
      }
      if (n['setting'] != null) {
        final key = n['setting'] as String;
        if (!types.containsKey(key)) throw _Unsupported('follows $key, which is not generated');
        return _camel(key);
      }
      if (n['hook'] != null && n['fallback'] != null) return _expr(n['fallback'] as Map<String, dynamic>, types);
      throw _Unsupported('${n['name']} is set at runtime');
    case 'color':
      return _colorLiteral(n['hex'] as String);
    case 'mix':
      final a = n['a'] as Map<String, dynamic>;
      final b = n['b'] as Map<String, dynamic>;
      String pct(Object? p) => p == null ? 'null' : _num(p as num);
      return 'kakaoMix(${_expr(a['color'] as Map<String, dynamic>, types)}, ${pct(a['percent'])}, '
          '${_expr(b['color'] as Map<String, dynamic>, types)}, ${pct(b['percent'])})';
    case 'length':
      return _num(n['px'] as num);
    case 'number':
      return _num(n['value'] as num);
    case 'percent':
      return _num((n['value'] as num) / 100);
    case 'duration':
      return 'Duration(microseconds: ${((n['ms'] as num) * 1000).round()})';
    case 'easing':
      final p = (n['bezier'] as List).cast<num>();
      return 'Cubic(${p.map(_num).join(', ')})';
    case 'em':
      return 'KakaoEm(${_num(n['factor'] as num)})';
    case 'viewport':
      return "KakaoViewportLength('${n['unit']}', ${_num(n['value'] as num)})";
    case 'calc':
      return _expr(n['expr'] as Map<String, dynamic>, types);
    case 'op':
      return '(${_expr(n['left'] as Map<String, dynamic>, types)} ${n['op']} ${_expr(n['right'] as Map<String, dynamic>, types)})';
    case 'shadow':
      final layers = (n['layers'] as List).cast<Map<String, dynamic>>();
      if (layers.any((l) => l['inset'] == true)) throw _Unsupported('inset shadow');
      return '[${layers.map((l) {
        String part(String k) => _expr(l[k] as Map<String, dynamic>, types);
        return 'BoxShadow(offset: Offset(${part('x')}, ${part('y')}), blurRadius: kakaoCssBlur(${part('blur')}), '
            'spreadRadius: ${part('spread')}, color: ${part('color')})';
      }).join(', ')}]';
    case 'list':
      // The padding shorthand: top, right, bottom, left; missing sides
      // repeat their opposite (CSS order), as EdgeInsets.fromLTRB.
      final items = (n['items'] as List).cast<Map<String, dynamic>>();
      if (!_isPadding(n)) throw _Unsupported('a list that is not a padding shorthand');
      final v = items.map((i) => _expr(i, types)).toList();
      final top = v[0];
      final right = v.length > 1 ? v[1] : top;
      final bottom = v.length > 2 ? v[2] : top;
      final left = v.length > 3 ? v[3] : right;
      return 'EdgeInsets.fromLTRB($left, $top, $right, $bottom)';
    case 'font':
      final w = n['weight'] as Map<String, dynamic>?;
      return 'KakaoFontSpec(size: ${_expr(n['size'] as Map<String, dynamic>, types)}, '
          'lineHeight: ${_expr(n['lineHeight'] as Map<String, dynamic>, types)}'
          '${w == null ? '' : ', weight: ${_expr(w, types)}'})';
    default:
      throw _Unsupported('a ${n['type']} value');
  }
}

/* ---- shared tokens -------------------------------------------------------------- */

String _sharedTokens() {
  final ts = tokens['tokens'] as Map<String, dynamic>;
  final b = StringBuffer()
    ..writeln("import 'package:flutter/animation.dart' show Cubic, Curve;")
    ..writeln()
    ..writeln('/// The shared tokens other than colours (`shared/tokens.css`).')
    ..writeln('abstract final class KakaoSharedTokens {');
  final skipped = <String>[];
  for (final MapEntry(key: name, value: t) in ts.entries) {
    final resolved = (t as Map<String, dynamic>)['resolved'] as Map<String, dynamic>;
    final type = _dartType(resolved);
    if (type == null || type == 'KakaoFontSpec') {
      skipped.add('$name (${resolved['type']})');
      continue;
    }
    String e;
    try {
      e = _expr(t['value'] as Map<String, dynamic>, const {});
    } on _Unsupported catch (u) {
      skipped.add('$name (${u.why})');
      continue;
    }
    b
      ..writeln('  /// `${t['property']}`')
      ..writeln('  static const $type ${_camel(name)} = $e;');
  }
  if (skipped.isNotEmpty) b.writeln('\n  // Not generated: ${skipped.join(', ')}.');
  b.writeln('}');
  return b.toString();
}

/* ---- component settings ------------------------------------------------------------- */

String _settings(String component) {
  final comp = (tokens['components'] as Map<String, dynamic>)[component] as Map<String, dynamic>?;
  if (comp == null) throw StateError('tokens.json has no component "$component"');
  final settings = (comp['settings'] as Map<String, dynamic>).cast<String, Map<String, dynamic>>();
  final cls = 'Kakao${_pascal(component)}Settings';

  Map<String, dynamic> firstResolved(Map<String, dynamic> s) => s['themed'] == true
      ? (s['resolved'] as Map<String, dynamic>).values.first as Map<String, dynamic>
      : s['resolved'] as Map<String, dynamic>;

  // Types, then expressions; drop settings that can't be expressed (and any
  // setting that follows one of those), repeating until stable.
  final types = <String, String>{};
  final skipped = <String, String>{};
  for (final MapEntry(key: k, value: s) in settings.entries) {
    var t = _dartType(firstResolved(s));
    // Only a padding setting reads a list of lengths as EdgeInsets (a
    // `margin` or `gap` list would need its own type).
    if (t == 'EdgeInsets' && !k.endsWith('padding')) t = null;
    if (t == null) {
      skipped[k] = firstResolved(s)['type'] as String;
    } else {
      types[k] = t;
    }
  }
  final exprs = <String, String>{};
  var changed = true;
  while (changed) {
    changed = false;
    exprs.clear();
    for (final k in types.keys.toList()) {
      try {
        exprs[k] = _expr(settings[k]!['value'] as Map<String, dynamic>, types);
      } on _Unsupported catch (u) {
        types.remove(k);
        skipped[k] = u.why;
        changed = true;
      }
    }
  }

  // Dependency order (a setting after the siblings it reads).
  final order = <String>[];
  final seen = <String>{};
  void visit(String k) {
    if (!seen.add(k)) return;
    for (final m in RegExp(r'(?<![.\w])([a-z][A-Za-z0-9]*)\b').allMatches(exprs[k]!)) {
      final dep = types.keys.firstWhere((x) => _camel(x) == m[1], orElse: () => '');
      if (dep.isNotEmpty && dep != k) visit(dep);
    }
    order.add(k);
  }

  types.keys.forEach(visit);

  final b = StringBuffer()
    ..writeln('// ignore_for_file: prefer_const_constructors')
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln("import '../theme/kakao_colors.g.dart';")
    ..writeln("import '../theme/kakao_tokens.g.dart';")
    ..writeln(
      exprs.values.any((e) => RegExp(r'kakaoMix|kakaoCssBlur|KakaoFontSpec|KakaoEm|KakaoViewportLength').hasMatch(e))
          ? "import '../theme/kakao_values.dart';\n"
          : '',
    )
    ..writeln('/// The settings block of `${comp['file']}` (`${comp['prefix']}*`), resolved')
    ..writeln('/// against a theme\'s colours. Lengths are logical pixels.');
  if (skipped.isNotEmpty) {
    b.writeln('///');
    b.writeln('/// Not generated (the widget handles these by hand):');
    for (final MapEntry(key: k, value: why) in skipped.entries) {
      b.writeln('/// - `${settings[k]!['property']}`: $why');
    }
  }
  b
    ..writeln('class $cls {')
    ..writeln('  const $cls._({')
    ..writeAll(types.keys.map((k) => '    required this.${_camel(k)},\n'))
    ..writeln('  });')
    ..writeln()
    ..writeln('  /// The defaults, with colour roles from [c] (the current theme, contrast')
    ..writeln('  /// mode and cross-fade applied).')
    ..writeln('  factory $cls.of(KakaoColors c) {');
  for (final k in order) {
    b.writeln('    final ${types[k]} ${_camel(k)} = ${exprs[k]};');
  }
  b
    ..writeln('    return $cls._(')
    ..writeAll(types.keys.map((k) => '      ${_camel(k)}: ${_camel(k)},\n'))
    ..writeln('    );')
    ..writeln('  }')
    ..writeln();
  for (final k in types.keys) {
    b
      ..writeln('  /// `${settings[k]!['property']}`')
      ..writeln('  final ${types[k]} ${_camel(k)};');
  }
  b
    ..writeln()
    ..writeln('  /// Every setting by its web name (the part after `${comp['prefix']}`).')
    ..writeln('  Map<String, Object> toMap() => {')
    ..writeAll(types.keys.map((k) => "    '$k': ${_camel(k)},\n"))
    ..writeln('  };')
    ..writeln('}');
  return b.toString();
}
