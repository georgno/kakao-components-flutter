#!/usr/bin/env node
// Interim: writes lib/src/theme/kakao_colors.g.dart from a kakao-components
// checkout (shared/tokens.css + shared/themes.css). Replaced by the
// tokens.json generator once kakao-components ships tools/export-tokens.js.
//
//   node tool/import-colors.mjs ../kakao-components
import fs from 'node:fs';
import path from 'node:path';

const src = process.argv[2] || '../kakao-components';
const tokens = fs.readFileSync(path.join(src, 'shared/tokens.css'), 'utf8');
const themes = fs.readFileSync(path.join(src, 'shared/themes.css'), 'utf8');
const version = (fs.readFileSync(path.join(src, 'index.html'), 'utf8').match(/<b>(v\d+\.\d+\.\d+)<\/b>/) || [])[1] || '?';

const decls = (body) => {
  const m = new Map();
  body.replace(/--kakao-color-([a-z-]+)\s*:\s*(#[0-9a-fA-F]{3,8})\s*;/g, (_, k, v) => m.set(k, v.toLowerCase()));
  return m;
};
const light = decls(tokens);
const roles = [...light.keys()];
const out = new Map([['light', { dark: false, colors: light }]]);

// @theme blocks: from the marker to the closing brace of the first rule.
for (const m of themes.matchAll(/\/\* @theme ([a-z]+) \*\/([\s\S]*?)\n}/g)) {
  const body = m[2];
  out.set(m[1], { dark: /color-scheme:\s*dark/.test(body), colors: new Map([...light, ...decls(body)]) });
}

// prefers-contrast: more overrides, per theme.
const contrast = new Map();
const cBlock = themes.slice(themes.indexOf('@media (prefers-contrast: more)'));
for (const m of cBlock.matchAll(/((?:\[data-kakao-theme="[a-z]+"\]|:root)[^{]*)\{([^}]*)\}/g)) {
  const names = [...m[1].matchAll(/data-kakao-theme="([a-z]+)"/g)].map((x) => x[1]);
  if (/:root/.test(m[1])) names.push('light');
  for (const n of new Set(names)) contrast.set(n, decls(m[2]));
}

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const hex = (v) => {
  let h = v.slice(1);
  if (h.length === 3) h = [...h].map((c) => c + c).join('');
  if (h.length === 6) h = 'ff' + h; else h = h.slice(6) + h.slice(0, 6);
  return `Color(0x${h.toUpperCase()})`;
};

let dart = `// GENERATED by tool/import-colors.mjs from kakao-components ${version}. Do not edit.
// Source: shared/tokens.css (light) and shared/themes.css (@theme blocks,
// prefers-contrast: more overrides).
// ignore_for_file: public_member_api_docs

import 'dart:ui' show Color;

/// The colour roles every kakao theme defines (\`--kakao-color-<role>\` on the web).
class KakaoColors {
  const KakaoColors({
${roles.map((r) => `    required this.${camel(r)},`).join('\n')}
  });

${roles.map((r) => `  /// \`--kakao-color-${r}\`\n  final Color ${camel(r)};`).join('\n')}

  KakaoColors copyWith({
${roles.map((r) => `    Color? ${camel(r)},`).join('\n')}
  }) => KakaoColors(
${roles.map((r) => `    ${camel(r)}: ${camel(r)} ?? this.${camel(r)},`).join('\n')}
  );

  /// Blends two themes' colours (the theme pickers' cross-fade).
  static KakaoColors lerp(KakaoColors a, KakaoColors b, double t) => KakaoColors(
${roles.map((r) => `    ${camel(r)}: Color.lerp(a.${camel(r)}, b.${camel(r)}, t)!,`).join('\n')}
  );

  @override
  bool operator ==(Object other) =>
      other is KakaoColors &&
${roles.map((r) => `      other.${camel(r)} == ${camel(r)}`).join(' &&\n')};

  @override
  int get hashCode => Object.hashAll([${roles.map(camel).join(', ')}]);
}

/// One kakao theme: its colours, and the stronger colours used when the
/// platform asks for more contrast.
class KakaoThemeData {
  const KakaoThemeData({required this.name, required this.isDark, required this.colors, required this.highContrast});
  final String name;
  final bool isDark;
  final KakaoColors colors;
  final KakaoColors highContrast;

  static const List<KakaoThemeData> all = [${[...out.keys()].map(camel).join(', ')}];

  static KakaoThemeData byName(String name) =>
      all.firstWhere((t) => t.name == name, orElse: () => light);
`;
for (const [name, t] of out) {
  const c = t.colors;
  const hc = new Map([...c, ...(contrast.get(name) || [])]);
  const block = (m) => roles.map((r) => `      ${camel(r)}: ${hex(m.get(r))},`).join('\n');
  dart += `
  static const KakaoThemeData ${camel(name)} = KakaoThemeData(
    name: '${name}',
    isDark: ${t.dark},
    colors: KakaoColors(
${block(c)}
    ),
    highContrast: KakaoColors(
${block(hc)}
    ),
  );
`;
}
dart += '}\n';
const dest = path.join(path.dirname(new URL(import.meta.url).pathname), '../lib/src/theme/kakao_colors.g.dart');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, dart);
console.log(`wrote ${path.relative(process.cwd(), dest)}: ${out.size} themes, ${roles.length} roles, contrast for ${[...contrast.keys()].join(', ')}`);
